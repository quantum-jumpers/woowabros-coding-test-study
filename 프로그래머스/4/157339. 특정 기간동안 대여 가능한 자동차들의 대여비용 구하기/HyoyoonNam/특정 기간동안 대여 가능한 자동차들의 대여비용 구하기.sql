SELECT      CR_CAR.CAR_ID, CR_CAR.CAR_TYPE,
            ROUND((DAILY_FEE * 30 - DAILY_FEE * 30 * DISCOUNT_RATE * 0.01), 0) as FEE

FROM        CAR_RENTAL_COMPANY_CAR as CR_CAR

# INNER JOIN  CAR_RENTAL_COMPANY_RENTAL_HISTORY as CR_HISTORY
#     ON      CR_CAR.CAR_ID = CR_HISTORY.CAR_ID
    
INNER JOIN  CAR_RENTAL_COMPANY_DISCOUNT_PLAN as CR_PLAN
    ON      CR_CAR.CAR_TYPE = CR_PLAN.CAR_TYPE
    
WHERE       CR_CAR.CAR_TYPE IN ('세단', 'SUV') AND
            # (END_DATE < '2022-11-01' OR START_DATE > '2022-11-30') AND
            DURATION_TYPE = '30일 이상' AND
            (DAILY_FEE * 30 - DAILY_FEE * 30 * DISCOUNT_RATE * 0.01) >= 500000 AND
            (DAILY_FEE * 30 - DAILY_FEE * 30 * DISCOUNT_RATE * 0.01) < 2000000 AND
            CR_CAR.CAR_ID NOT IN
            (
                SELECT  CAR_ID
                FROM    CAR_RENTAL_COMPANY_RENTAL_HISTORY
                WHERE   START_DATE <= '2022-11-30' AND
                        END_DATE >= '2022-11-01'
            )

ORDER BY    FEE DESC, CR_CAR.CAR_TYPE ASC, CR_CAR.CAR_ID DESC;